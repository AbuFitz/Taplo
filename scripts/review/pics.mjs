import { chromium } from "@playwright/test"
const w=Number(process.argv[2]??1366), h=Number(process.argv[3]??768)
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" })
const p = await (await b.newContext({ viewport:{width:w,height:h}, reducedMotion:"reduce", hasTouch:w<600, isMobile:w<600 })).newPage()
p.on("pageerror",e=>console.log("ERR",e.message.slice(0,200)))
await p.goto("http://localhost:3000/onboarding"); await p.evaluate(()=>localStorage.clear()); await p.reload()
await p.getByLabel(/Business name/).fill("Bright Learning")
await p.locator('input[type=file]').first().setInputFiles("public/businesses/brightlearn/logo.webp")
await p.waitForTimeout(1500); await p.screenshot({path:"docs/screens/r9/pics-1-crop.png"})
await p.getByTestId("crop-apply").click(); await p.waitForTimeout(1200); await p.screenshot({path:"docs/screens/r9/pics-2-logo.png"})
await p.getByRole("button",{name:/^Continue$/}).click(); await p.waitForTimeout(600)
await p.getByRole("radio",{name:"Photo"}).check({force:true}); await p.waitForTimeout(800)
await p.screenshot({path:"docs/screens/r9/pics-3-photo.png"})
await p.locator('input[type=file]').last().setInputFiles("public/showcase/originals/interior-studio.webp")
await p.waitForTimeout(1500); await p.screenshot({path:"docs/screens/r9/pics-4-cropcover.png"})
await p.getByTestId("crop-apply").click(); await p.waitForTimeout(1500); await p.screenshot({path:"docs/screens/r9/pics-5-cover.png"})
await b.close()
