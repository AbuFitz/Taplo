for (const width of [390, 1440]) test(`visual setup keeps each decision separate and the real page responds at ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: width < 1024 ? 844 : 950 })
  await page.goto('/onboarding')
  await page.getByLabel('Business name', { exact: true }).fill('North Street Studio')
  await expect(page.getByLabel('A line under your name')).not.toBeVisible()
  const next = () => page.getByRole('button', { name: 'Continue', exact: true }).click()
  await next()
  await expect(page.getByRole('list', { name: 'Kinds of business' }).locator('img')).toHaveCount(0)
  await page.getByRole('button', { name: 'Barber', exact: true }).click()
  await expect(page.getByTestId('goal')).toHaveCount(0)
  await expect(page.getByTestId('reach')).toHaveCount(0)
  await expect.poll(() => page.getByRole('button', { name: 'Barber', exact: true }).evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(17, 17, 17)')
  await page.screenshot({ path: path.join(process.env.TAPLO_REVIEW_DIR ?? 'test-results', `setup-business-types-${width}.png`) })
  await next()
  await page.getByRole("button",{name:"Change main action",exact:true}).click(); await page.getByRole('radio', { name: /Book with me/ }).check(); await page.getByRole("button",{name:"Done",exact:true}).click()
  await expect(page.getByRole('heading', { name: 'How can customers reach you?' })).toBeVisible()
  await expect(page.getByTestId('reach').getByRole('textbox')).toHaveCount(1)
  await page.getByLabel('Email', { exact: true }).fill('studio@example.com')
  await next()
  await page.getByLabel('Service 1 name').fill('Haircut')
  await page.getByLabel('Service 1 price').fill('22')
  await page.getByLabel('Service 1 minutes').fill('30')
  await next()
  await expect(page.getByRole('heading', { name: 'Choose your layout.' })).toBeVisible()
  await page.getByTestId('look-picker').locator('label').filter({ has: page.locator('input[value="ink"]') }).click()
  const position = await page.evaluate(() => scrollY)
  await page.getByTestId('look-picker').locator('label').filter({ has: page.locator('input[value="service"]') }).click()
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(position)
  await page.getByTestId('look-picker').locator('label').filter({ has: page.locator('input[value="ink"]') }).click()
  if (width < 1024) {
    expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight + 1)).toBe(true)
    await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeInViewport()
  }
  const frame = page.frameLocator('iframe[data-testid="setup-live-page"]:visible').first()
  await expect(frame.locator('[data-taplo-page]')).toHaveAttribute('data-tone', 'dark')
  await expect(frame.getByRole('heading', { level: 1 })).toHaveText('North Street Studio')
  await frame.locator('[data-taplo-page]').evaluate(() => Promise.all(document.getAnimations().filter(animation=>animation.effect?.getComputedTiming().iterations!==Infinity).map(animation => animation.finished.catch(() => undefined))))
  await page.screenshot({ path: path.join(process.env.TAPLO_REVIEW_DIR ?? 'test-results', `setup-live-theme-${width}.png`) })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
  expect(axe.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) }))).toEqual([])
  await page.reload()
  await expect(page.getByTestId('look-picker').getByRole('radio', { name: /Midnight/ })).toBeChecked()
  await next()
  await page.getByRole('button', { name: 'Publish my page', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Saved as your page')
  const draft = await page.evaluate(() => JSON.parse(localStorage.getItem('taplo.demo.v2')!))
  expect(draft.content.identity.name).toBe('North Street Studio')
  expect(draft.content.services[0]).toMatchObject({ name: 'Haircut', priceMinor: 2200 })
  expect(draft.content.testimonials).toEqual([])
  expect(draft.content.gallery).toEqual([])
  expect(draft.published.page.themeId).toBe('ink')
})

