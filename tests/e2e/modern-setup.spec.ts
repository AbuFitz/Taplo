test('changing the hero preview width preserves a customer booking already in progress', async ({ page }) => {
  await page.goto('/')
  const frame = page.frameLocator('[data-testid="home-live-page"]')
  await frame.getByRole('button', { name: 'Book a haircut', exact: true }).click()
  const flow = frame.getByTestId('booking-flow')
  await flow.getByTestId('bk-service').first().click()
  await flow.getByRole('button', { name: /Anyone available/ }).click()
  await flow.getByTestId('bk-slot').first().click()
  await flow.getByRole('button', { name: /Book this time/ }).click()
  await flow.getByLabel('Your name', { exact: true }).fill('Preview visitor')
  await page.getByRole('button', { name: 'Desktop view', exact: true }).click()
  await expect(flow.getByLabel('Your name', { exact: true })).toHaveValue('Preview visitor')
  await expect.poll(() => frame.locator('html').evaluate(el => el.clientWidth)).toBeGreaterThanOrEqual(1024)
})
