import { expect, test } from "@playwright/test"
import AxeBuilder from "@axe-core/playwright"
import path from "node:path"
import { addWidget } from "./helpers"

for (const width of [390, 1440]) test(`visual setup keeps each decision separate and the real page responds at ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: 950 })
  await page.goto('/onboarding')
  await page.getByLabel('Business name', { exact: true }).fill('North Street Studio')
  await expect(page.getByLabel('A line under your name')).not.toBeVisible()
  const next = () => page.getByRole('button', { name: 'Continue', exact: true }).click()
  await next()
  await page.getByRole('button', { name: 'Barber', exact: true }).click()
  await expect(page.getByTestId('goal')).toHaveCount(0)
  await expect(page.getByTestId('reach')).toHaveCount(0)
  await page.screenshot({ path: path.join(process.env.TAPLO_REVIEW_DIR ?? 'test-results', `setup-business-types-${width}.png`) })
  await next()
  await expect(page.getByRole('heading', { name: 'What should people do first?' })).toBeVisible()
  await page.getByRole('radio', { name: /Book with me/ }).check()
  await next()
  await expect(page.getByRole('heading', { name: 'How can people reach you?' })).toBeVisible()
  await expect(page.getByTestId('reach').getByRole('textbox')).toHaveCount(1)
  await page.getByLabel('Email', { exact: true }).fill('studio@example.com')
  await next()
  await page.getByLabel('Service 1 name').fill('Haircut')
  await page.getByLabel('Service 1 price').fill('22')
  await page.getByLabel('Service 1 minutes').fill('30')
  await next()
  await expect(page.getByRole('heading', { name: 'Choose a design' })).toBeVisible()
  await page.getByTestId('look-picker').locator('label').filter({ has: page.locator('input[value="apex"]') }).click()
  const frame = page.frameLocator('iframe[title="Live preview of your page"]:visible').first()
  await expect(frame.locator('[data-taplo-page]')).toHaveAttribute('data-tone', 'dark')
  await expect(frame.getByRole('heading', { level: 1 })).toHaveText('North Street Studio')
  await page.screenshot({ path: path.join(process.env.TAPLO_REVIEW_DIR ?? 'test-results', `setup-live-theme-${width}.png`) })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
  expect(axe.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) }))).toEqual([])
  await page.reload()
  await expect(page.getByTestId('look-picker').getByRole('radio', { name: /Apex/ })).toBeChecked()
  await next()
  await page.getByRole('button', { name: 'Publish my page', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Saved as your page')
  const draft = await page.evaluate(() => JSON.parse(localStorage.getItem('taplo.demo.v2')!))
  expect(draft.content.identity.name).toBe('North Street Studio')
  expect(draft.content.services[0]).toMatchObject({ name: 'Haircut', priceMinor: 2200 })
  expect(draft.content.testimonials).toEqual([])
  expect(draft.content.gallery).toEqual([])
  expect(draft.published.page.themeId).toBe('apex')
})

for (const width of [390, 1440]) test(`homepage scene switches actual responsive documents at ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: 950 })
  await page.goto('/')
  const frame = page.frameLocator('[data-testid="home-live-page"]')
  await expect(frame.getByRole('heading', { level: 1 })).toHaveText('Jay’s Barbers')
  await expect.poll(() => frame.locator('html').evaluate(el => ({ width:el.clientWidth,height:el.clientHeight }))).toEqual({width:390,height:844})
  const handsetRatio = await page.locator('.live-stage-device').evaluate(el => el.clientWidth / el.clientHeight)
  expect(Math.abs(handsetRatio - 390/844)).toBeLessThan(.002)
  await page.getByRole('button', { name: 'Car dealer', exact: true }).click()
  await expect(frame.getByRole('heading', { level: 1 })).toHaveText('Harris Cars')
  await page.getByRole('button', { name: 'Desktop view', exact: true }).click()
  await expect.poll(() => frame.locator('html').evaluate(el => el.clientWidth)).toBeGreaterThanOrEqual(1024)
  await page.getByRole('button', { name: 'Angled view', exact: true }).click()
  await expect(page.locator('.live-stage-space')).toHaveAttribute('data-angle', 'false')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: path.join(process.env.TAPLO_REVIEW_DIR ?? 'test-results', `modern-home-${width}.png`) })
})

test('Google review setup preserves old records but never publishes them as Google content', async ({ page }) => {
  await page.goto('/dashboard')
  await page.getByRole('button', { name: 'Try Jay’s Barbers', exact: true }).click()
  await page.waitForURL('**/dashboard/page')
  const original = await page.evaluate(() => JSON.parse(localStorage.getItem('taplo.demo.v2')!).content.testimonials)
  await page.goto('/dashboard/reviews')
  await expect(page.getByRole('heading', { name: 'Google reviews', exact: true })).toBeVisible()
  await expect(page.getByLabel('Customer name')).toHaveCount(0)
  await expect(page.getByLabel('What they said')).toHaveCount(0)
  await page.getByLabel('Google Maps or review link', { exact: true }).fill('https://www.google.com/maps/place/Example')
  await page.getByLabel('Google Maps or review link', { exact: true }).blur()
  await expect(page.getByRole('link', { name: 'Open on Google' })).toHaveAttribute('href', 'https://www.google.com/maps/place/Example')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('taplo.demo.v2')!).content.testimonials)).toEqual(original)
  await page.goto('/dashboard/page')
  await addWidget(page, /^Google reviews/)
  await page.goto('/demo/preview')
  await expect(page.locator('[data-widget="reviews"]').getByRole('link')).toHaveAttribute('href', 'https://www.google.com/maps/place/Example')
  for (const review of original ?? []) await expect(page.getByText(review.quote, { exact: true })).toHaveCount(0)
  await expect(page.locator('[data-widget="reviews"]')).not.toContainText(/★|out of 5|Shared by the business/)
})

