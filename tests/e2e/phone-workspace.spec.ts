import { expect, test } from "@playwright/test"
import path from "node:path"

for (const width of [320, 390, 768, 1440]) test(`shared phone and concise profile keep working through setup at ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto("/onboarding")
  const phone = page.locator(".setup-canvas .phone-shell")
  const frame = page.frameLocator('iframe[data-testid="setup-live-page"]')
  await page.getByLabel("Business name", { exact: true }).fill("North Street Studio")
  await page.getByLabel("Short description (optional)", { exact: true }).fill("Independent hair studio in St Albans.")
  await expect(frame.getByRole("heading", { level: 1 })).toHaveText("North Street Studio")
  await expect(phone.locator(".phone-island")).toHaveCount(1)
  const hardware = await phone.boundingBox(), screen = await phone.locator(".phone-screen").boundingBox()
  expect(hardware!.width / hardware!.height).toBeCloseTo(398 / 852, 2)
  expect((hardware!.width - screen!.width) / 2).toBeLessThan(5)
  expect(await frame.locator("html").evaluate(el => getComputedStyle(el).scrollbarWidth)).toBe("none")
  await frame.locator("body").evaluate(el => el.dataset.previewContinuity = "same-page")
  await expect.poll(() => page.locator('iframe[data-testid="setup-live-page"]').evaluate(el => getComputedStyle(el).opacity)).toBe("1")
  await page.screenshot({ path: path.join(process.env.TAPLO_REVIEW_DIR ?? "test-results", `profile-phone-${width}.png`) })
  if (width >= 1024) {
    const workspace = await page.locator("main.setup-flow").boundingBox()
    expect(workspace!.x).toBeGreaterThanOrEqual(30)
    expect(workspace!.y).toBeGreaterThanOrEqual(30)
    const canvas = await page.locator(".setup-canvas").boundingBox()
    expect(hardware!.y + hardware!.height).toBeGreaterThan(canvas!.y + canvas!.height)
    await expect(page.getByTestId("setup-backdrop")).toBeVisible()
  }
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("What do you do?")
  await expect(page.getByRole("heading", { level: 1 })).toBeFocused()
  await expect(frame.locator("body")).toHaveAttribute("data-preview-continuity", "same-page")
  await page.getByRole("button", { name: "Back", exact: true }).click()
  await expect(page.getByLabel("Business name", { exact: true })).toHaveValue("North Street Studio")
  await expect(page.getByRole("button", { name: "Continue", exact: true })).toBeInViewport()
  expect(await page.evaluate(() => scrollY)).toBe(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

for (const width of [390, 1440]) test(`theme choices show actual style samples at ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto("/onboarding")
  const next = () => page.getByRole("button", { name: "Continue", exact: true }).click()
  await page.getByLabel("Business name", { exact: true }).fill("North Street Studio"); await next()
  await page.getByRole("button", { name: "Barber", exact: true }).click(); await next()
  await page.getByLabel("Email", { exact: true }).fill("studio@example.com"); await next()
  await page.getByLabel("Service 1 name").fill("Cut and finish")
  await page.getByLabel("Service 1 price").fill("28")
  await page.getByLabel("Service 1 minutes").fill("30"); await next()
  const picker = page.getByTestId("look-picker")
  await expect(picker.locator("img")).toHaveCount(0)
  await expect(picker.locator(".theme-swatch-type")).toHaveCount(6)
  await picker.locator("label").filter({ has: page.locator('input[value="ink"]') }).click()
  const frame = page.frameLocator('iframe[data-testid="setup-live-page"]')
  await expect(frame.locator("[data-taplo-page]")).toHaveAttribute("data-tone", "dark")
  const surface = await frame.locator("[data-taplo-page]").evaluate(el => getComputedStyle(el).getPropertyValue("--tp-background").trim())
  await expect.poll(() => page.locator(".setup-canvas [data-preview-mode]").evaluate(el => getComputedStyle(el).getPropertyValue("--phone-surface").trim())).toBe(surface)
  await expect(page.getByRole("button", { name: "Continue", exact: true })).toBeInViewport()
  await expect.poll(() => page.locator('iframe[data-testid="setup-live-page"]').evaluate(el => getComputedStyle(el).opacity)).toBe("1")
  await page.screenshot({ path: path.join(process.env.TAPLO_REVIEW_DIR ?? "test-results", `theme-phone-${width}.png`) })
})
